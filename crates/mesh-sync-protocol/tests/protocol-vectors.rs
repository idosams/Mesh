#[test]
fn the_corpus_covers_every_message_exactly_once() {
    let mut seen: Vec<&str> = every_message()
        .iter()
        .map(|message| message.kind().as_str())
        .collect();
    seen.sort_unstable();
    let mut expected: Vec<&str> = MESSAGE_KINDS.iter().map(|kind| kind.as_str()).collect();
    expected.sort_unstable();
    assert_eq!(seen, expected);
}

#[test]
fn every_message_round_trips_through_the_wire() {
    for message in every_message() {
        let bytes = encode_message(&message);
        let decoded = decode_message(&bytes).unwrap_or_else(|error| {
            panic!("{} did not decode: {error}", message.kind());
        });
        assert_eq!(decoded, message, "{} did not round trip", message.kind());
        assert_eq!(
            encode_message(&decoded),
            bytes,
            "{} re-encoded to different bytes",
            message.kind()
        );
    }
}

#[test]
fn every_message_matches_its_published_vector() {
    for (message, (name, expected)) in every_message().iter().zip(VECTORS) {
        assert_eq!(
            message.kind().as_str(),
            name,
            "the vector table is out of order"
        );
        let actual = to_hex(&encode_message(message));
        let pinned: String = expected.chars().filter(|c| !c.is_whitespace()).collect();
        assert_eq!(actual, pinned, "{name} no longer encodes to its vector");
    }
}

#[test]
fn every_published_vector_decodes_to_the_message_it_names() {
    for (message, (name, expected)) in every_message().iter().zip(VECTORS) {
        let pinned: String = expected.chars().filter(|c| !c.is_whitespace()).collect();
        let bytes = from_hex(&pinned);
        let decoded = decode_message(&bytes)
            .unwrap_or_else(|error| panic!("the published {name} vector does not decode: {error}"));
        assert_eq!(&decoded, message);
    }
}

#[test]
fn every_message_in_the_corpus_satisfies_its_own_preconditions() {
    for message in every_message() {
        assert_eq!(
            message.check(),
            Ok(()),
            "{} is in the corpus but is not well formed",
            message.kind()
        );
    }
}

/// Bytes from lowercase hex. Panics on bad input, which is a broken test rather than bad data.
fn from_hex(text: &str) -> Vec<u8> {
    assert!(text.len() % 2 == 0, "a hex vector has an even length");
    (0..text.len() / 2)
        .map(|index| {
            u8::from_str_radix(&text[index * 2..index * 2 + 2], 16)
                .unwrap_or_else(|_| panic!("not hex at byte {index}"))
        })
        .collect()
}
