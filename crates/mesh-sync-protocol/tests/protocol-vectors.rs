//! The published wire vectors: one instance of every CWP message, with its exact bytes.
//!
//! # Why the bytes are pinned here and not only round-tripped
//!
//! A round-trip test proves this implementation agrees with itself. An external implementer —
//! `01KZC2TBX5BGTQPXXX2DATM3TY` builds one from the specification alone — needs to know whether it
//! agrees with *us*, and for that it needs bytes. The table below is those bytes.
//!
//! A change to any line here is a wire-format change. It is legitimate exactly when the message
//! set changed on purpose and `docs/protocol.md` §7.3 changed in the same commit; it is a defect
//! every other time, which is what makes the pin worth having.

