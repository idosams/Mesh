#[derive(Debug)]
struct RunOptions {
    workload: String,
    benchmark_id: Option<String>,
    seed: u64,
    parameters: JsonObject,
    iterations: u64,
    warmup: u64,
    cache_state: CacheState,
    repo: PathBuf,
    data: PathBuf,
    out: Option<PathBuf>,
    policy: SinkPolicy,
}

impl Default for RunOptions {
    fn default() -> Self {
        RunOptions {
            workload: String::new(),
            benchmark_id: None,
            seed: 42,
            parameters: JsonObject::new(),
            iterations: 100,
            warmup: 10,
            cache_state: CacheState::Warm,
            repo: PathBuf::from("."),
            data: PathBuf::from("."),
            out: None,
            policy: SinkPolicy::PUBLISHABLE,
        }
    }
}

fn parse_run_options(arguments: &[String]) -> Result<RunOptions, String> {
    let mut options = RunOptions::default();
    let mut index = 0;
    while index < arguments.len() {
        let flag = arguments[index].as_str();
        if flag == "--exploratory" {
            options.policy = SinkPolicy::EXPLORATORY;
            index += 1;
            continue;
        }
        let value = arguments
            .get(index + 1)
            .cloned()
            .ok_or_else(|| format!("`{flag}` needs a value"))?;
        match flag {
            "--workload" => options.workload = value,
            "--benchmark-id" => options.benchmark_id = Some(value),
            "--seed" => options.seed = parse_u64("--seed", &value)?,
            "--param" => {
                let (key, text) = value
                    .split_once('=')
                    .ok_or_else(|| format!("`--param {value}` must be KEY=VALUE"))?;
                options.parameters = options.parameters.with(key, parse_param_value(text));
            }
            "--iterations" => options.iterations = parse_u64("--iterations", &value)?,
            "--warmup" => options.warmup = parse_u64("--warmup", &value)?,
            "--cache" => {
                options.cache_state = CacheState::from_word(&value)
                    .ok_or_else(|| format!("`--cache {value}` must be `warm` or `cold`"))?;
            }
            "--repo" => options.repo = PathBuf::from(value),
            "--data" => options.data = PathBuf::from(value),
            "--out" => options.out = Some(PathBuf::from(value)),
            other => return Err(format!("unknown option `{other}`\n\n{USAGE}")),
        }
        index += 2;
    }
    if options.workload.is_empty() {
        return Err(format!(
            "`run` needs `--workload NAME`; registered: {}",
            WorkloadRegistry::builtin().names().join(", ")
        ));
    }
    Ok(options)
}

/// Whole numbers stay numbers, booleans stay booleans; everything else is
/// recorded verbatim as a string.
fn parse_param_value(text: &str) -> Json {
    text.parse::<u64>().map_or_else(
        |_| match text {
            "true" => Json::Bool(true),
            "false" => Json::Bool(false),
            other => Json::string(other),
        },
        Json::Uint,
    )
}

fn parse_u64(flag: &str, text: &str) -> Result<u64, String> {
    text.parse::<u64>()
        .map_err(|error| format!("`{flag} {text}` is not a whole number: {error}"))
}

fn run(arguments: &[String], invocation: &str) -> Result<i32, String> {
    let options = parse_run_options(arguments)?;
    let registry = WorkloadRegistry::builtin();
    let mut workload = registry
        .build(&options.workload, options.seed, &options.parameters)
        .map_err(|error| error.to_string())?;

    let benchmark_id = options
        .benchmark_id
        .clone()
        .unwrap_or_else(|| format!("mesh-bench/{}", options.workload));
    let config = RunConfig::new(benchmark_id, invocation)
        .with_cache_state(options.cache_state)
        .with_iterations(options.iterations)
        .with_warmup_iterations(options.warmup);

    let harness = Harness::new(
        MonotonicClock::new(),
        SystemWallClock,
        SystemProbe::new(&options.repo, &options.data),
    );

    match harness
        .run(workload.as_mut(), &config)
        .map_err(|error| error.to_string())?
    {
        RunOutcome::VerificationFailed(failure) => {
            eprintln!("mesh-bench: {failure}");
            Ok(EXIT_REFUSED)
        }
        RunOutcome::Measured(result) => {
            // The row is printed only once it has been accepted. Printing first
            // and consulting the sink afterwards emitted every percentile of a
            // refused run to stdout while stderr said "nothing written" — and a
            // refused row on a terminal is one copy-paste from being quoted.
            // With no `--out`, stdout *is* the sink and no policy applies.
            let Some(path) = options.out else {
                println!("{}", result.to_json_pretty());
                return Ok(EXIT_OK);
            };
            let mut sink = ValidatingSink::new(FileWriter::new(&path), options.policy);
            match sink.accept(&result) {
                Ok(()) => {
                    println!("{}", result.to_json_pretty());
                    eprintln!("mesh-bench: appended 1 row to {}", path.display());
                    Ok(EXIT_OK)
                }
                Err(error) => {
                    eprintln!("mesh-bench: row refused, nothing written: {error}");
                    Ok(EXIT_REFUSED)
                }
            }
        }
    }
}

fn validate(arguments: &[String]) -> Result<i32, String> {
    if arguments.is_empty() {
        return Err("`validate` needs at least one file".to_owned());
    }
    let mut refused = 0_usize;
    let mut accepted = 0_usize;
    for path in arguments {
        let contents = std::fs::read_to_string(path)
            .map_err(|error| format!("cannot read {path}: {error}"))?;
        for (number, line) in contents.lines().enumerate() {
            if line.trim().is_empty() {
                continue;
            }
            match BenchmarkResult::from_json_text(line) {
                Ok(_) => accepted += 1,
                Err(error) => {
                    refused += 1;
                    eprintln!("{path}:{}: {error}", number + 1);
                }
            }
        }
    }
    println!("{accepted} rows accepted, {refused} refused");
    Ok(if refused == 0 { EXIT_OK } else { EXIT_REFUSED })
}

fn compare_files(arguments: &[String]) -> Result<i32, String> {
    let [baseline_path, candidate_path] = arguments else {
        return Err("`compare` needs exactly two files".to_owned());
    };
    let baseline = last_row(baseline_path)?;
    let candidate = last_row(candidate_path)?;
    // A results file accumulates rows. Comparing the last one silently is
    // correct and unreadable: the reader cannot tell whether a surprising
    // verdict came from the row they meant or from one of nine others.
    eprintln!("mesh-bench: baseline  {}", baseline.provenance);
    eprintln!("mesh-bench: candidate {}", candidate.provenance);
    let report = compare(&baseline.result, &candidate.result, VarianceBand::STATED)
        .map_err(|error| error.to_string())?;
    print!("{report}");
    if report.within_band() {
        return Ok(EXIT_OK);
    }
    eprintln!(
        "mesh-bench: {} percentile(s) outside the stated band — the instrument is not trustworthy yet",
        report.breaches().len()
    );
    Ok(EXIT_REFUSED)
}

/// A row plus where in its file it came from.
#[derive(Debug)]
struct SelectedRow {
    result: BenchmarkResult,
    provenance: String,
}

/// How many non-blank rows a results file holds.
///
/// Split out from IO so the count reported to the reader is testable without a
/// file on disk.
fn row_count(contents: &str) -> usize {
    contents
        .lines()
        .filter(|line| !line.trim().is_empty())
        .count()
}

/// The last row of `path`, and a phrase naming which row that was.
///
/// `compare` always takes the last row; the phrase is what stops that from
/// being a silent choice when the file holds more than one.
fn last_row(path: &str) -> Result<SelectedRow, String> {
    let contents =
        std::fs::read_to_string(path).map_err(|error| format!("cannot read {path}: {error}"))?;
    let total = row_count(&contents);
    let line = contents
        .lines()
        .rfind(|line| !line.trim().is_empty())
        .ok_or_else(|| format!("{path} holds no result rows"))?;
    let result =
        BenchmarkResult::from_json_text(line).map_err(|error| format!("{path}: {error}"))?;
    Ok(SelectedRow {
        provenance: format!("row {total} of {total} (the last) in {path}"),
        result,
    })
}

/// What `corpus` was asked to do.
#[derive(Clone, Debug, PartialEq, Eq)]
struct CorpusOptions {
    workload: Option<WorkloadId>,
    scale: Scale,
    seed: u64,
    content: bool,
    root: Option<PathBuf>,
}

impl Default for CorpusOptions {
    fn default() -> Self {
        CorpusOptions {
            workload: None,
            scale: Scale::Full,
            seed: CANONICAL_SEED,
            content: false,
            root: None,
        }
    }
}

fn parse_corpus_options(arguments: &[String]) -> Result<CorpusOptions, String> {
    let mut options = CorpusOptions::default();
    let mut index = 0;
    while index < arguments.len() {
        let flag = arguments[index].as_str();
        if flag == "--content" {
            options.content = true;
            index += 1;
            continue;
        }
        let value = arguments
            .get(index + 1)
            .cloned()
            .ok_or_else(|| format!("`{flag}` needs a value"))?;
        match flag {
            "--workload" => {
                options.workload = Some(WorkloadId::parse(&value).ok_or_else(|| {
                    format!(
                        "`--workload {value}` is not one of: {}",
                        WORKLOADS
                            .iter()
                            .map(|id| id.code())
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                })?);
            }
            "--scale" => {
                options.scale = Scale::parse(&value).ok_or_else(|| {
                    format!(
                        "`--scale {value}` is not one of: {}",
                        SCALES
                            .iter()
                            .map(|scale| scale.name())
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                })?;
            }
            "--seed" => options.seed = parse_u64("--seed", &value)?,
            "--root" => options.root = Some(PathBuf::from(value)),
            other => return Err(format!("unknown option `{other}`\n\n{USAGE}")),
        }
        index += 2;
    }
    Ok(options)
}

/// `mesh-bench corpus …` — the workload datasets: plan §12.2's W1–W6 and W7.
fn corpus_verb(arguments: &[String]) -> Result<i32, String> {
    let subcommand = arguments.first().map(String::as_str);
    let rest = arguments.get(1..).unwrap_or_default();
    match subcommand {
        Some("list") => {
            for id in WORKLOADS {
                let scales = SCALES
                    .iter()
                    .map(|scale| scale.name())
                    .collect::<Vec<_>>()
                    .join(" ");
                println!("{}\t{}\t{scales}", id.code(), id.title());
            }
            Ok(EXIT_OK)
        }
        Some("describe") => corpus_describe(rest),
        Some("digest") => corpus_digest(rest),
        Some("materialize") => corpus_materialize(rest),
        Some(other) => Err(format!("unknown corpus subcommand `{other}`\n\n{USAGE}")),
        None => Err(format!("`corpus` needs a subcommand\n\n{USAGE}")),
    }
}

/// Builds the generator the options name, or explains what is missing.
fn corpus_generator(options: &CorpusOptions) -> Result<Box<dyn corpus::Generator>, String> {
    let workload = options
        .workload
        .ok_or_else(|| "`corpus` needs `--workload W1..W7`".to_owned())?;
    Ok(corpus::build(workload, options.scale, options.seed))
}

fn corpus_describe(arguments: &[String]) -> Result<i32, String> {
    let options = parse_corpus_options(arguments)?;
    let generator = corpus_generator(&options)?;
    let mut described = generator
        .describe()
        .as_object()
        .cloned()
        .unwrap_or_else(JsonObject::new);
    if options.content {
        described = described.with("content_digest", Json::string(generator.content_digest()));
    }
    println!("{}", to_string_pretty(&Json::Object(described)));
    // A corpus that does not match its stated shape is refused here for the
    // same reason a failed verification refuses a timing number: a dataset that
    // is not what it says it is cannot support a measurement made on it.
    Ok(corpus_shape_verdict(generator.as_ref()))
}

fn corpus_digest(arguments: &[String]) -> Result<i32, String> {
    let options = parse_corpus_options(arguments)?;
    let generator = corpus_generator(&options)?;
    let mut row = JsonObject::new()
        .with("workload", Json::string(generator.id().code()))
        .with("scale", Json::string(generator.scale().name()))
        .with("seed", Json::Uint(generator.seed()))
        .with("generator_version", Json::string(corpus::GENERATOR_VERSION))
        .with("plan_digest", Json::string(generator.plan_digest()));
    if options.content {
        row = row.with("content_digest", Json::string(generator.content_digest()));
    }
    println!("{}", to_string_pretty(&Json::Object(row)));
    Ok(corpus_shape_verdict(generator.as_ref()))
}

fn corpus_materialize(arguments: &[String]) -> Result<i32, String> {
    let options = parse_corpus_options(arguments)?;
    let generator = corpus_generator(&options)?;
    let root = options
        .root
        .clone()
        .ok_or_else(|| "`corpus materialize` needs `--root DIR`".to_owned())?;
    if !generator.shape().holds() {
        return Ok(corpus_shape_verdict(generator.as_ref()));
    }
    match corpus::materialize::materialize(generator.as_ref(), &root) {
        Ok(report) => {
            let row = JsonObject::new()
                .with("workload", Json::string(generator.id().code()))
                .with("scale", Json::string(generator.scale().name()))
                .with("seed", Json::Uint(generator.seed()))
                .with("root", Json::string(root.display().to_string()))
                .with("plan_digest", Json::string(generator.plan_digest()))
                .with("written", report.to_json());
            println!("{}", to_string_pretty(&Json::Object(row)));
            Ok(EXIT_OK)
        }
        Err(error) => {
            eprintln!("mesh-bench: corpus not written: {error}");
            Ok(EXIT_REFUSED)
        }
    }
}

/// Reports every shape fact that does not hold, and returns the exit code.
fn corpus_shape_verdict(generator: &dyn corpus::Generator) -> i32 {
    let report = generator.shape();
    if report.holds() {
        return EXIT_OK;
    }
    for fact in report.violations() {
        eprintln!(
            "mesh-bench: {} {} shape violation: {} stated {} observed {} tolerance {}",
            generator.id().code(),
            generator.scale().name(),
            fact.name,
            fact.stated,
            fact.observed,
            fact.tolerance
        );
    }
    EXIT_REFUSED
}

#[cfg(test)]
mod tests {
    use super::*;

    fn arguments(words: &[&str]) -> Vec<String> {
        words.iter().map(|word| (*word).to_owned()).collect()
    }

    #[test]
    fn run_options_take_their_defaults() {
        let options = parse_run_options(&arguments(&["--workload", "blob-scan"])).expect("parses");
        assert_eq!(options.workload, "blob-scan");
        assert_eq!(options.seed, 42);
        assert_eq!(options.iterations, 100);
        assert_eq!(options.cache_state, CacheState::Warm);
        assert_eq!(options.policy, SinkPolicy::PUBLISHABLE);
    }

    #[test]
    fn run_options_parse_every_flag() {
        let options = parse_run_options(&arguments(&[
            "--workload",
            "blob-scan",
            "--benchmark-id",
            "mesh/x",
            "--seed",
            "7",
            "--param",
            "blob_count=4",
            "--param",
            "label=tiny",
            "--iterations",
            "5",
            "--warmup",
            "1",
            "--cache",
            "cold",
            "--out",
            "rows.jsonl",
            "--exploratory",
        ]))
        .expect("parses");
        assert_eq!(options.benchmark_id.as_deref(), Some("mesh/x"));
        assert_eq!(options.seed, 7);
        assert_eq!(options.iterations, 5);
        assert_eq!(options.warmup, 1);
        assert_eq!(options.cache_state, CacheState::Cold);
        assert_eq!(options.out, Some(PathBuf::from("rows.jsonl")));
        assert_eq!(options.policy, SinkPolicy::EXPLORATORY);
        assert_eq!(
            options.parameters.get("blob_count").and_then(Json::as_u64),
            Some(4)
        );
        assert_eq!(
            options.parameters.get("label").and_then(Json::as_str),
            Some("tiny")
        );
    }

    #[test]
    fn a_missing_workload_is_a_usage_error() {
        let error = parse_run_options(&arguments(&[])).expect_err("workload is required");
        assert!(error.contains("--workload"));
    }

    #[test]
    fn an_unknown_cache_word_is_refused() {
        let error = parse_run_options(&arguments(&["--workload", "x", "--cache", "lukewarm"]))
            .expect_err("closed vocabulary");
        assert!(error.contains("warm"));
    }

    #[test]
    fn a_flag_without_a_value_is_refused() {
        let error = parse_run_options(&arguments(&["--workload"])).expect_err("dangling flag");
        assert!(error.contains("needs a value"));
    }

    #[test]
    fn parameters_keep_their_type() {
        assert_eq!(parse_param_value("12"), Json::Uint(12));
        assert_eq!(parse_param_value("true"), Json::Bool(true));
        assert_eq!(parse_param_value("4k"), Json::string("4k"));
    }

    #[test]
    fn verify_schema_exits_zero_on_this_build() {
        let code = dispatch(&arguments(&["mesh-bench", "verify-schema"])).expect("dispatches");
        assert_eq!(code, EXIT_OK);
    }

    #[test]
    fn unknown_verbs_are_usage_errors() {
        let error = dispatch(&arguments(&["mesh-bench", "benchmark"])).expect_err("unknown verb");
        assert!(error.contains("unknown verb"));
    }

    #[test]
    fn row_counting_ignores_blank_lines() {
        assert_eq!(row_count(""), 0);
        assert_eq!(row_count("\n  \n"), 0);
        assert_eq!(row_count("a\nb\n"), 2);
        assert_eq!(row_count("a\n\nb\n\n"), 2);
    }

    #[test]
    fn compare_names_which_row_of_how_many_it_took() {
        let path = std::env::temp_dir().join(format!(
            "mesh-bench-provenance-{}-{}.jsonl",
            std::process::id(),
            line!()
        ));
        let row =
            mesh_bench::json::to_string_compact(&mesh_bench::testing::sample_result().to_json());
        std::fs::write(&path, format!("{row}\n{row}\n\n{row}\n")).expect("fixture written");

        let selected = last_row(path.to_str().expect("utf-8 path")).expect("reads the last row");
        assert!(
            selected.provenance.contains("row 3 of 3"),
            "the reader must be told which row was compared: {}",
            selected.provenance
        );
        std::fs::remove_file(&path).expect("cleanup");
    }

    #[test]
    fn a_file_with_no_rows_is_named_rather_than_compared() {
        let path = std::env::temp_dir().join(format!(
            "mesh-bench-empty-{}-{}.jsonl",
            std::process::id(),
            line!()
        ));
        std::fs::write(&path, "\n\n").expect("fixture written");
        let error = last_row(path.to_str().expect("utf-8 path")).expect_err("no rows to compare");
        assert!(error.contains("no result rows"), "{error}");
        std::fs::remove_file(&path).expect("cleanup");
    }

    #[test]
    fn validate_refuses_a_file_of_incomplete_rows() {
        let path =
            std::env::temp_dir().join(format!("mesh-bench-cli-{}.jsonl", std::process::id()));
        let complete = mesh_bench::testing::sample_result().to_json();
        let incomplete = complete.without_path("hardware.cpu_model");
        std::fs::write(
            &path,
            format!(
                "{}\n{}\n",
                mesh_bench::json::to_string_compact(&complete),
                mesh_bench::json::to_string_compact(&incomplete)
            ),
        )
        .expect("fixture written");

        let code =
            validate(&arguments(&[path.to_str().expect("utf-8 path")])).expect("validate runs");
        assert_eq!(code, EXIT_REFUSED);
        std::fs::remove_file(&path).expect("cleanup");
    }
}
