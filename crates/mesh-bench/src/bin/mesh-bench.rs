//! `mesh-bench` — the runner CLI in front of the harness.
//!
//! Seven verbs, no configuration files, no network:
//!
//! ```text
//! mesh-bench run --workload <name> [--seed N] [--param k=v]… [--out FILE]
//! mesh-bench validate <file.jsonl>…
//! mesh-bench compare <baseline.jsonl> <candidate.jsonl>
//! mesh-bench fields
//! mesh-bench workloads
//! mesh-bench verify-schema
//! mesh-bench corpus list|describe|digest|materialize …
//! ```
//!
//! Exit codes are the contract for scripts: `0` accepted, `1` refused (an
//! incomplete row, a failed verification, a breached variance band, a corpus
//! that does not match its stated shape), `2` the command itself was wrong.

use mesh_bench::clock::{MonotonicClock, SystemWallClock};
use mesh_bench::corpus::{self, Scale, WorkloadId, CANONICAL_SEED, SCALES, WORKLOADS};
use mesh_bench::env::SystemProbe;
use mesh_bench::harness::{Harness, RunConfig, RunOutcome};
use mesh_bench::json::{to_string_pretty, Json, JsonObject};
use mesh_bench::schema::{BenchmarkResult, CacheState, REQUIRED_FIELDS};
use mesh_bench::selfcheck;
use mesh_bench::sink::{FileWriter, SinkPolicy, ValidatingSink};
use mesh_bench::variance::{compare, VarianceBand};
use mesh_bench::workloads::WorkloadRegistry;
use std::path::PathBuf;

/// Accepted.
const EXIT_OK: i32 = 0;
/// Refused: the row, the run or the comparison did not hold up.
const EXIT_REFUSED: i32 = 1;
/// The invocation was wrong.
const EXIT_USAGE: i32 = 2;

fn main() {
    let arguments: Vec<String> = std::env::args().collect();
    let code = match dispatch(&arguments) {
        Ok(code) => code,
        Err(error) => {
            eprintln!("mesh-bench: {error}");
            EXIT_USAGE
        }
    };
    std::process::exit(code);
}

fn dispatch(arguments: &[String]) -> Result<i32, String> {
    let verb = arguments.get(1).map(String::as_str);
    let rest = arguments.get(2..).unwrap_or_default();
    match verb {
        Some("run") => run(rest, &arguments.join(" ")),
        Some("validate") => validate(rest),
        Some("compare") => compare_files(rest),
        Some("fields") => {
            for field in REQUIRED_FIELDS {
                println!("{field}");
            }
            Ok(EXIT_OK)
        }
        Some("workloads") => {
            for name in WorkloadRegistry::builtin().names() {
                println!("{name}");
            }
            Ok(EXIT_OK)
        }
        Some("corpus") => corpus_verb(rest),
        Some("verify-schema") => {
            let report = selfcheck::run();
            println!("{report}");
            Ok(if report.passed() {
                EXIT_OK
            } else {
                EXIT_REFUSED
            })
        }
        Some("--help" | "-h" | "help") | None => {
            println!("{USAGE}");
            Ok(EXIT_OK)
        }
        Some(other) => Err(format!("unknown verb `{other}`\n\n{USAGE}")),
    }
}

