//! Bakes the build profile into the binary.
//!
//! The build facts (`rustc` version, target triple, profile, opt-level,
//! debug-assertion state) cannot be probed at run time without guessing, and a
//! guessed build profile is exactly the metadata lie the result schema exists
//! to prevent — a `debug` number published as a `release` number is off by an
//! order of magnitude. Cargo knows all five at compile time, so they are
//! captured here and read back through `env::build_info`.

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=PROFILE");
    println!("cargo:rerun-if-env-changed=OPT_LEVEL");
    println!("cargo:rerun-if-env-changed=DEBUG");
    println!("cargo:rerun-if-env-changed=TARGET");
    println!("cargo:rerun-if-env-changed=RUSTC");

    let profile = required_env("PROFILE");
    let opt_level = required_env("OPT_LEVEL");
    let debug = required_env("DEBUG");
    let target = required_env("TARGET");
    let rustc_version = rustc_version();

    let contents = format!(
        "// @generated by crates/mesh-bench/build.rs — do not edit.\n\
         /// The `rustc --version` string of the compiler that built this binary.\n\
         pub const RUSTC_VERSION: &str = {rustc_version:?};\n\
         /// The target triple this binary was compiled for.\n\
         pub const TARGET_TRIPLE: &str = {target:?};\n\
         /// The Cargo profile name (`debug`, `release`, …) used for this build.\n\
         pub const PROFILE: &str = {profile:?};\n\
         /// The optimisation level (`0`, `1`, `2`, `3`, `s`, `z`) used for this build.\n\
         pub const OPT_LEVEL: &str = {opt_level:?};\n\
         /// Whether debug info was requested for this build (Cargo's `DEBUG`).\n\
         pub const DEBUG_INFO: &str = {debug:?};\n"
    );

    let out_dir = PathBuf::from(required_env("OUT_DIR"));
    fs::write(out_dir.join("build_info.rs"), contents).expect("write build_info.rs");
}

fn required_env(key: &str) -> String {
    env::var(key).unwrap_or_else(|_| panic!("cargo must set {key} for build scripts"))
}

/// Asks the exact compiler Cargo is driving for its version string.
fn rustc_version() -> String {
    let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_owned());
    let output = Command::new(rustc)
        .arg("--version")
        .output()
        .expect("invoke rustc --version");
    assert!(
        output.status.success(),
        "rustc --version exited with a failure code"
    );
    String::from_utf8(output.stdout)
        .expect("rustc --version emits utf-8")
        .trim()
        .to_owned()
}
